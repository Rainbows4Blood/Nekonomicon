import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { parseHTML } from "linkedom";
import { labels } from "./model.js";

test("actual renderer handles all run states and committed progress", async () => {
  const { window, document } = parseHTML(await readFile(new URL("index.html", import.meta.url), "utf8"));
  globalThis.window = window;
  globalThis.document = document;
  // linkedom has a read-only select.value; browsers supply this native setter.
  for (const select of document.querySelectorAll("select")) {
    Object.defineProperty(select, "value", { configurable: true, get() { return this.querySelector("option[selected]")?.value ?? this.querySelector("option")?.value ?? ""; }, set(value) { for (const option of this.querySelectorAll("option")) option.selected = option.value === String(value); } });
  }
  const initial = { state: "ready", storageReady: true, connectionReady: true, catalogued: 40, authNote: "Checked", dataFolder: "fixture" };
  let event, rows = [];
  window.go = { main: { App: { Snapshot: async () => initial, Profiles: async () => [], Failures: async () => rows } } };
  window.runtime = { EventsOn: (name, callback) => { assert.equal(name, "progress"); event = callback; } };
  await import("./app.js?renderer-test");
  const $ = id => document.getElementById(id);
  for (const state of Object.keys(labels)) {
    const running = ["starting", "discovering", "fetching", "covers", "pausing"].includes(state);
    const held = running || ["paused", "blocked_auth", "blocked_storage"].includes(state);
    const phase = state === "discovering" ? "discover" : state === "covers" ? "covers" : "fetch";
    event({ ...initial, state, running, phase, run: held ? { mode: "refresh", phase, covers: true } : null, saved: 4, eligible: 10, productErrors: 1, queued: 2, coverSaved: 2, coverTotal: 3, coverScanDone: false, connectionReady: state !== "setup" && state !== "blocked_auth", message: "Fixture outcome" });
    assert.equal($("phase").textContent, labels[state]);
    assert.equal($("catalogued").textContent, "40");
    assert.equal($("mode").disabled, held);
    assert.equal($("source").disabled, held);
    if (state === "discovering") assert.equal($("progress").hasAttribute("value"), false);
    if (state === "paused") assert.equal($("primary").textContent, "Resume crawl");
    if (state === "blocked_auth") assert.equal($("primary").disabled, true);
    if (state === "pausing") assert.equal($("primary").disabled, true);
    if (state === "fetching") assert.match($("count").textContent, /4 \/ 10 saved this run · 1 failed/);
  }
  event({ ...initial, state: "fetching", phase: "fetch", running: true, sitemapsSkipped: 1 });
  assert.equal($("sitemapSkipped").hidden, false);
  assert.equal($("sitemapSkipped").textContent, "1 sitemap skipped by the site's robots policy.");
  event({ ...initial, sitemapsSkipped: 0 });
  assert.equal($("sitemapSkipped").hidden, true);
  // Stage highlighting must follow the held run, including cover-only work.
  event({ ...initial, state: "covers", phase: "covers", running: true, cataloguedCovers: 17, run: { mode: "covers", phase: "covers", covers: false } });
  assert.equal($("stepCovers").getAttribute("aria-current"), "step");
  assert.equal($("stepDiscover").dataset.skipped, "true");
  assert.equal($("stepFetch").dataset.skipped, "true");
  assert.equal($("cataloguedCovers").textContent, "17");
  event({ ...initial, state: "paused", phase: "fetch", run: { mode: "retry", phase: "fetch", covers: false } });
  assert.equal($("stepFetch").getAttribute("aria-current"), "step");
  assert.equal($("stepDiscover").dataset.skipped, "true");
  assert.equal($("stepCovers").dataset.skipped, "true");
  event(initial);
  assert.equal(document.querySelector('[aria-current="step"]'), null);
  $("websiteCookie").value = "synthetic";
  $("apiCookie").value = "synthetic";
  event({ ...initial, source: "dmsguild", websiteHost: "www.dmsguild.com", apiHost: "api.dmsguild.com", probeID: 170778, connectionReady: false });
  assert.equal($("source").value, "dmsguild");
  assert.equal($("testID").value, "170778");
  assert.equal($("websiteCookie").placeholder, "www.dmsguild.com");
  assert.equal($("apiCookie").placeholder, "api.dmsguild.com");
  assert.equal($("websiteCookie").value, "");
  assert.equal($("apiCookie").value, "");
  assert.equal($("primary").disabled, true);
  // Maintenance is explicit, source-scoped, and available without sign-in.
  let maintenanceActions = [];
  window.go.main.App.RefreshMaintenance = async () => {};
  window.go.main.App.StartMaintenance = async action => { maintenanceActions.push(action); };
  window.go.main.App.MaintenanceIssues = async () => [{ id: 42, status: "warnings", message: "<script>unsafe</script>", warnings: ["pagecount: invalid"] }];
  const schemaRequired = { needsSchema: true, schemaVersion: 2, state: "schema_required", summary: {} };
  event({ ...initial, storageAvailable: true, storageReady: false, connectionReady: false, maintenance: schemaRequired });
  assert.equal($("primary").disabled, true);
  assert.equal($("maintenanceGate").hidden, false);
  assert.equal($("applySchema").disabled, false);
  assert.equal($("extractMetadata").disabled, true);
  assert.deepEqual(maintenanceActions, []);
  $("maintenanceTab").onclick();
  assert.equal($("maintenancePanel").hidden, false);
  assert.equal($("crawlPanel").hidden, true);
  assert.equal($("maintenanceTab").getAttribute("aria-selected"), "true");
  assert.equal($("workspaceTitle").textContent, "Data maintenance");
  $("maintenanceTab").onkeydown({ key: "ArrowUp", preventDefault() {} });
  assert.equal($("crawlPanel").hidden, false);
  assert.equal($("workspaceTitle").textContent, "Crawler");
  // linkedom's tabIndex getter treats zero as -1; inspect the reflected attribute.
  assert.equal($("crawlTab").getAttribute("tabindex"), "0");
  assert.equal($("maintenanceTab").getAttribute("tabindex"), "-1");
  $("crawlTab").onkeydown({ key: "ArrowDown", preventDefault() {} });
  assert.equal($("maintenancePanel").hidden, false);
  await new Promise(resolve => setTimeout(resolve, 0));
  // Grouping owns the catalog independently and offers the correct resume action.
  event({ ...initial, storageAvailable: true, maintenance: {state:"paused", action:"groups", held:true, groups:{total:12,current:4,pending:8}, job:{processed:4,total:12}} });
  assert.equal($("buildGroups").textContent,"Resume grouping");
  assert.equal($("buildGroups").disabled,false);
  assert.equal($("extractMetadata").disabled,true);
  assert.equal($("source").disabled,true);
  assert.equal($("groupsPending").textContent,"8");
  event({ ...initial, storageAvailable:true, maintenance:{state:"grouping",action:"groups",held:true,running:true,groups:{pending:8},job:{processed:4,total:12}} });
  assert.equal($("buildGroups").disabled,true);
  assert.equal($("maintenanceState").textContent,"Building D&D groups");
  assert.equal($("maintenanceProgress").value,4);
  event({ ...initial, storageAvailable:true, maintenance:{state:"completed",action:"groups",groups:{current:12,pending:0}} });
  assert.equal($("buildGroups").disabled,true);
  event({ ...initial, storageAvailable: true, storageReady: false, maintenance: schemaRequired });
  const task = { state: "extracting", running: true, held: true, needsSchema: false, summary: { total: 100, current: 0, pending: 100 }, job: { processed: 64, total: 100, warned: 2, failed: 1 } };
  event({ ...initial, storageAvailable: true, maintenance: task });
  assert.equal($("source").disabled, true);
  assert.equal($("primary").disabled, true);
  assert.equal($("chooseFolder").disabled, true);
  assert.equal($("maintenanceProgress").value, 64);
  assert.equal($("maintenanceProgress").max, 100);
  assert.equal($("pauseMaintenance").hidden, false);
  event({ ...initial, storageAvailable: true, maintenance: { ...task, running: false, state: "paused" } });
  assert.equal($("extractMetadata").textContent, "Resume extraction");
  assert.equal($("extractMetadata").disabled, false);
  assert.equal($("endMaintenance").disabled, false);
  await $("reloadMetadataIssues").onclick();
  assert.equal($("metadataIssueList").querySelector("script"), null);
  assert.match($("metadataIssueList").textContent, /unsafe/);
  $("crawlTab").onclick();
  assert.equal($("crawlPanel").hidden, false);
  rows = [{ id: 7, phase: "product", kind: "schema", status: 200, message: "<img src=x onerror=alert(1)>" }];
  $("activity").open = true;
  await $("reloadErrors").onclick();
  assert.equal($("errors").querySelector("img"), null);
  assert.match($("errors").textContent, /onerror/);
  event({ ...initial, loading: true, migrating: true, busy: true, storageReady: false, loadingMessage: "Copying saved products…" });
  assert.equal($("loadingOverlay").hidden, false);
  assert.equal($("appContent").hasAttribute("inert"), true);
  assert.equal($("appContent").getAttribute("aria-busy"), "true");
  assert.equal($("loadingTitle").textContent, "Upgrading your catalog");
  assert.equal($("loadingMessage").textContent, "Copying saved products…");
  assert.equal($("abortLoading").disabled, false);
  assert.equal($("source").disabled, true);
  event({ ...initial, loadingError: "Catalog upgrade could not finish" });
  assert.equal($("loadingOverlay").hidden, true);
  assert.equal($("appContent").hasAttribute("inert"), false);
  assert.match($("notice").textContent, /could not finish/);
  event(initial);
  assert.equal($("notice").hidden, true);
  event({ ...initial, loading: true, migrating: true, busy: true, storageReady: false });
  let aborts = 0;
  window.go.main.App.AbortAndClose = async () => { aborts++; };
  await $("abortLoading").onclick();
  await $("abortLoading").onclick();
  assert.equal(aborts, 1);
  assert.equal($("loadingOverlay").hidden, false);
  assert.equal($("abortLoading").disabled, true);
  assert.equal($("loadingTitle").textContent, "Closing Nekonomicon");
  delete globalThis.window;
  delete globalThis.document;
});
